export type Preset = {
  title: string; type: 'habit' | 'target'; count?: number; per?: 'day' | 'week'; unit: string;
  options?: number[]; months?: number; weight?: boolean; amt?: boolean; step?: number; stepLabel?: string;
};
const H = (title: string, count: number, per: 'day' | 'week', unit: string): Preset => ({ title, type: 'habit', count, per, unit });
const G = (title: string, unit: string, options: number[], months: number, extra: Partial<Preset> = {}): Preset => ({ title, type: 'target', unit, options, months, ...extra });
const ONCE = (title: string, months = 1) => G(title, 'done', [1], months);

